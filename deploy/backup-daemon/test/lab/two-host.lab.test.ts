  test("RESTORE DRILL runs on host B (its own disk and CPU) and primary commit throughput on host A is not stalled", async () => {
    const tAfterDelta = await mark();
    lab.psql(auditRows(76, 80), "pg_audit_db");
    const linesNow = Number(lab.psql("SELECT count(*) FROM journal_lines;"));
    const tFinal = await mark();
    await tail();

    // Asynchronous on purpose: a blocking benchmark would freeze this process's event loop for the whole drill window
    // (and let the HTTPS keep-alive socket to the daemon go stale), and would not actually overlap the drills.
    // Rate-limited (-R): the question is whether the drills STALL commits, not how much WAL the Wi-Fi link can carry.
    const RATE = 3000;
    const bench = (seconds: number): Promise<{ tps: number; latencyMs: number }> =>
      new Promise((resolve) => {
        const script = join(lab.root, "bench.sql");
        writeFileSync(script, "INSERT INTO heartbeat DEFAULT VALUES;\n");
        const child = spawn("pgbench", ["-n", "-h", join(lab.root, "sock"), "-p", String(lab.pgPort), "-U", "postgres", "-c", "4", "-R", String(RATE), "-T", String(seconds), "-f", script, "payment_gateway_prod"], { stdio: ["ignore", "pipe", "pipe"] });
        let out = "";
        child.stdout.on("data", (chunk: Buffer) => { out += chunk.toString("utf8"); });
        child.on("close", () => resolve({ tps: Number(/tps = ([0-9.]+)/.exec(out)?.[1] ?? 0), latencyMs: Number(/latency average = ([0-9.]+) ms/.exec(out)?.[1] ?? 0) }));
      });
    const havePgbench = which("pgbench") !== null;
    const baseline = havePgbench ? await bench(10) : { tps: 0, latencyMs: 0 };

    // The benchmark runs for the whole window while drills run back to back on host B.
    let benchDone = false;
    const duringPromise = havePgbench ? bench(40).finally(() => { benchDone = true; }) : Promise.resolve({ tps: 0, latencyMs: 0 }).finally(() => { benchDone = true; });
    const startedAt = Date.now();
    let drills = 0;
    let report: DrillReport;
    do {
      report = await runDrillWith({ targetTime: tFinal });
      drills += 1;
      expect(report.errorMessage).toBeUndefined();
      expect(report.status).toBe("PASSED");
      expect(Number(report.doubleEntryDrift)).toBe(0);
      expect(report.balanceMismatches).toBe(0);
      expect(report.auditBrokenLinks).toBe(0);
      expect(report.journalLineCount).toBe(linesNow);
    } while (!benchDone && drills < 40);
    const drillWindowSeconds = Math.round((Date.now() - startedAt) / 1000);
    const during = await duringPromise;

    expect(report.checks.auditChain.detail).toContain("verified 80 audit rows");
    expect(verifyDrillReportSignature(report, "9f3a7c1e5b2d84f06a1c3e7b9d2f4a8c5e0b6d1a3f7c9e2b4d8a0c6e1f5b3a79")).toBe(true);
    void tAfterDelta;

    // the scratch cluster lived on B and is gone; A never hosted it; the production archive was not polluted
    expect(ssh("ls /var/lib/pg-backup/scratch | wc -l", { sudo: true })).toBe("0");
    expect(remoteWalKeys().filter((key) => /\/00000002/.test(key))).toEqual([]);
    expect(Number(ssh("pgrep -c -x postgres || true", { sudo: true, allowFail: true }) || "0")).toBe(0);
    if (havePgbench) {
      console.log(
        `[two-host lab] ${drills} full restore drills ran on host B over ${drillWindowSeconds}s; ` +
          `primary on A at ${RATE} tps target: baseline ${baseline.tps.toFixed(0)} tps / ${baseline.latencyMs.toFixed(2)} ms, ` +
          `during drills ${during.tps.toFixed(0)} tps / ${during.latencyMs.toFixed(2)} ms`,
      );
      expect(drills).toBeGreaterThanOrEqual(3);
      expect(during.tps).toBeGreaterThan(baseline.tps * 0.8); // commits were not stalled
      expect(during.latencyMs).toBeLessThan(Math.max(5, baseline.latencyMs * 3));
    }
  }, 600_000);

