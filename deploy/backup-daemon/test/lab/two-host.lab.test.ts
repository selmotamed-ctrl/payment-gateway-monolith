/** One retry for reads: a pooled keep-alive socket the server already closed shows up as ECONNRESET on first use. */
const api = async <T = Record<string, unknown>>(path: string, method = "GET", body?: unknown): Promise<{ status: number; json: T }> => {
  try {
    return await apiOnce<T>(path, method, body);
  } catch (error) {
    if (method === "GET" && (error as NodeJS.ErrnoException).code === "ECONNRESET") return apiOnce<T>(path, method, body);
    throw error;
  }
};

const apiOnce = <T = Record<string, unknown>>(path: string, method = "GET", body?: unknown): Promise<{ status: number; json: T }> =>
  new Promise((resolve, reject) => {
    const payload = body === undefined ? undefined : JSON.stringify(body);
    const request = https.request(
      {
        host: B_HOST,
        port: lab.daemonPort,
        path,
        method,
        agent: lab.agent,
        timeout: 60_000,
        headers: payload === undefined ? {} : { "content-type": "application/json", "content-length": Buffer.byteLength(payload) },
      },
      (response) => {
        const chunks: Buffer[] = [];
        response.on("data", (chunk: Buffer) => chunks.push(chunk));
        response.on("end", () => resolve({ status: response.statusCode ?? 0, json: JSON.parse(Buffer.concat(chunks).toString("utf8") || "{}") as T }));
      },
    );
    request.on("timeout", () => request.destroy(new Error("daemon request timed out")));
    request.on("error", reject);
    request.end(payload);
  });

interface RunRow { id: string; status: string; storageTargets: string[]; errorMessage?: string }
const runBackup = async (kind: "full" | "delta"): Promise<RunRow> => {
  const accepted = await api<{ backupJobId: string }>("/v1/backups/trigger", "POST", { target: "all", kind });
  expect(accepted.status).toBe(202);
  const id = accepted.json.backupJobId;
  return waitFor(`backup ${id}`, async () => {
    const runs = (await api<{ runs: RunRow[] }>("/v1/runs?limit=50")).json.runs;
    const run = runs.find((candidate) => candidate.id === id);
    return run && (run.status === "PASSED" || run.status === "FAILED") ? run : null;
  }, 300_000);
};
