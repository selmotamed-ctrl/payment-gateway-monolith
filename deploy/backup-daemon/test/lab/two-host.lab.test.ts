const generateCerts = (dir: string, bIp: string): void => {
  const run = (args: string[]) => {
    const result = spawnSync("openssl", args, { cwd: dir, encoding: "utf8" });
    if (result.status !== 0) throw new Error(`openssl ${args.join(" ")}: ${result.stderr}`);
  };
  run(["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", "ca.key", "-out", "ca.crt", "-days", "2", "-subj", "/CN=Lab CA"]);
  for (const [name, san] of [["backup-daemon", `subjectAltName=IP:${bIp},DNS:localhost`], ["backup-client", "subjectAltName=DNS:backup-client"], ["wal-archive-client", "subjectAltName=DNS:wal-archive-client"]] as const) {
    writeFileSync(join(dir, `${name}.ext`), `${san}\n`);
    run(["req", "-newkey", "rsa:2048", "-nodes", "-keyout", `${name}.key`, "-out", `${name}.csr`, "-subj", `/CN=${name}`]);
    run(["x509", "-req", "-in", `${name}.csr`, "-CA", "ca.crt", "-CAkey", "ca.key", "-CAcreateserial", "-out", `${name}.crt`, "-days", "2", "-extfile", `${name}.ext`]);
  }
};

