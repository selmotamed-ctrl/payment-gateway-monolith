const ssh = (script: string, options: { sudo?: boolean; allowFail?: boolean; timeoutMs?: number } = {}): string => {
  const remote = options.sudo ? "sudo -S -p '' bash -s" : "bash -s";
  const input = options.sudo ? `${B_PASSWORD}\n${script}\n` : `${script}\n`;
  const result = spawnSync("sshpass", ["-e", "ssh", ...sshBase, `${B_USER}@${B_HOST}`, remote], { input, encoding: "utf8", env: sshEnv, timeout: options.timeoutMs ?? 300_000 });
  if (result.status !== 0 && !options.allowFail) {
    throw new Error(`ssh failed (${result.status}): ${(result.stderr || result.stdout).slice(0, 600)}\n--- script ---\n${script.slice(0, 400)}`);
  }
  return `${result.stdout ?? ""}`.trim();
};

const rsyncTo = (localDir: string, remoteDir: string, excludes: string[] = []): void => {
  const result = spawnSync(
    "sshpass",
    ["-e", "rsync", "-a", "--delete", ...excludes.flatMap((pattern) => ["--exclude", pattern]), "-e", `ssh ${sshBase.join(" ")}`, `${localDir}/`, `${B_USER}@${B_HOST}:${remoteDir}/`],
    { encoding: "utf8", env: sshEnv, timeout: 300_000 },
  );
  if (result.status !== 0) throw new Error(`rsync failed: ${result.stderr.slice(0, 400)}`);
};

const localAddressTo = (host: string): string => {
  const result = spawnSync("ip", ["-4", "route", "get", host], { encoding: "utf8" });
  const match = /src (\d+\.\d+\.\d+\.\d+)/.exec(result.stdout);
  if (!match) throw new Error("cannot determine the local address that routes to host B");
  return match[1]!;
};

