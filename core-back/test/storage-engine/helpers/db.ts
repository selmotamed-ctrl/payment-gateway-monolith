const auditDdl = (schema: string): string => `
CREATE TABLE ${schema}.audit_records (
  seq_no              BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id                  UUID         PRIMARY KEY,
  created_at          TIMESTAMPTZ  NOT NULL,
  ingested_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  actor_id            UUID         NOT NULL,
  actor_email         VARCHAR(191) NULL,
  role                VARCHAR(64)  NOT NULL,
  action              VARCHAR(96)  NOT NULL,
  entity_type         VARCHAR(64)  NOT NULL,
  entity_id           VARCHAR(64)  NOT NULL,
  merchant_id         UUID         NULL,
  approval_request_id UUID         NULL,
  request_id          VARCHAR(64)  NULL,
  client_ip           VARCHAR(45)  NULL,
  user_agent          TEXT         NULL,
  before_json         JSONB        NOT NULL,
  after_json          JSONB        NOT NULL,
  prev_hash           CHAR(64)     NOT NULL,
  row_hash            CHAR(64)     NOT NULL
);

CREATE INDEX ${schema}_audit_entity_idx
  ON ${schema}.audit_records (entity_type, entity_id, created_at DESC, id DESC);

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE OR REPLACE FUNCTION ${schema}.compute_audit_chain_hash_trg() RETURNS trigger AS $$
DECLARE
  v_prev_hash CHAR(64);
  v_canonical TEXT;
BEGIN
  PERFORM pg_advisory_xact_lock(994001);
  NEW.seq_no := nextval(pg_get_serial_sequence('${schema}.audit_records', 'seq_no'));
  SELECT row_hash INTO v_prev_hash
  FROM ${schema}.audit_records
  ORDER BY seq_no DESC
  LIMIT 1;
  IF v_prev_hash IS NULL THEN
    v_prev_hash := repeat('0', 64);
  END IF;
  NEW.prev_hash := v_prev_hash;
  v_canonical := concat_ws(
    '|',
    NEW.prev_hash,
    NEW.id::text,
    to_char(NEW.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    NEW.actor_id::text,
    NEW.action,
    NEW.entity_type,
    NEW.entity_id,
    NEW.before_json::text,
    NEW.after_json::text
  );
  NEW.row_hash := encode(digest(v_canonical, 'sha256'), 'hex');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_chain_compute
  BEFORE INSERT ON ${schema}.audit_records
  FOR EACH ROW EXECUTE FUNCTION ${schema}.compute_audit_chain_hash_trg();

CREATE OR REPLACE FUNCTION ${schema}.forbid_audit_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'AUDIT_TAMPER_PROHIBITED: audit_records is strictly append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_immutable
  BEFORE UPDATE OR DELETE OR TRUNCATE ON ${schema}.audit_records
  FOR EACH STATEMENT EXECUTE FUNCTION ${schema}.forbid_audit_mutation();
`;

export interface AuditSandbox {
  schema: string;
  table: string;
  pool: Pool;
  driver: DedicatedAuditDatabaseDriver;
  cleanup: () => Promise<void>;
}

export const createAuditSandbox = async (
  prefix = "audit",
): Promise<AuditSandbox> => {
  const schema = safeSchemaName(prefix);
  const admin = createPool({ max: 1 });
  await admin.query(`CREATE SCHEMA ${schema}`);
  await admin.query(auditDdl(schema));
  await admin.end();

  const pool = createPool({ max: 6 });
  const table = `${schema}.audit_records`;
  return {
    schema,
    table,
    pool,
    driver: new DedicatedAuditDatabaseDriver(pool, table),
    cleanup: async () => {
      await pool.end().catch(() => undefined);
      await dropSchema(schema);
    },
  };
};

