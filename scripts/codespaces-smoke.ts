#!/usr/bin/env bun
/**
 * Smoke test of a RUNNING local stack (started with `./scripts/codespaces-start.sh`, profile merchant-demo
 * or full). It drives the real HTTP endpoints - nothing is mocked - and exits non-zero on any failure:
 *
 *   1. health of the merchant, checkout and Fake Rails backends and both portals
 *   2. core-back refuses a client WITHOUT a certificate (mTLS is enforced)
 *   3. the dev merchant logs in, seeds the Sandbox Studio demo data and creates a Sandbox payment link
 *   4. the payer opens the checkout page and pays with the Edfali OTP rail using a Fake Rails persona wallet
 *   5. the confirm step ends SUCCEEDED and the merchant sees the SUCCEEDED payment
 *   6. a payment by a payer who is not the persona does not succeed (negative control)
 *
 *   ./scripts/codespaces-start.sh smoke          # or: bun scripts/codespaces-smoke.ts
 *
 * Credentials come from .local/codespaces/secrets.env (generated by the launcher) or from the environment
 * variables DEV_PASSWORD and FAKE_RAILS_ADMIN_PASSWORD.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SECRETS_FILE = process.env.CODESPACES_SECRETS_FILE ?? join(ROOT, ".local", "codespaces", "secrets.env");

const secret = (name: string): string => {
  if (process.env[name]) return process.env[name]!;
  if (existsSync(SECRETS_FILE)) {
    const match = new RegExp(`^${name}=(.*)$`, "m").exec(readFileSync(SECRETS_FILE, "utf8"));
    if (match) return match[1]!.trim().replace(/^'(.*)'$/, "$1");
  }
  throw new Error(`${name} not found in the environment or ${SECRETS_FILE} - start the stack first`);
};

const port = (name: string, fallback: number): number => Number(process.env[name] ?? fallback);
const MERCHANT = `http://127.0.0.1:${port("MERCHANT_BACK_PORT", 4102)}/api/v1`;
const CHECKOUT = `http://127.0.0.1:${port("CHECKOUT_BACK_PORT", 4103)}/api/v1`;
const FAKE = `http://127.0.0.1:${port("FAKE_RAILS_BACK_PORT", 4104)}`;
const CORE_URL = `https://127.0.0.1:${port("CORE_PORT", 4000)}`;
const PORTALS: Array<[string, number]> = [
  ["merchant portal", port("MERCHANT_FRONT_PORT", 5102)],
  ["checkout portal", port("CHECKOUT_FRONT_PORT", 5103)],
  ["Fake Rails portal", port("FAKE_RAILS_FRONT_PORT", 5104)],
];

/** A persona wallet seeded by Fake Rails (high balance); any other number is an unknown payer. */
const PERSONA_MOBILE = "0910000001";
const UNKNOWN_MOBILE = "0919999999";

type Json = Record<string, any>;
/** Every probe is bounded: a hung edge must fail the smoke test, not hang CI. */
const fetchWithTimeout = (url: string, init: RequestInit = {}): Promise<Response> =>
  fetch(url, { ...init, signal: AbortSignal.timeout(15_000) });
const call = async (method: string, url: string, headers: Record<string, string> = {}, body?: unknown) => {
  const response = await fetchWithTimeout(url, {
    method,
    headers: { "content-type": "application/json", ...headers },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let json: Json = {};
  try {
    json = JSON.parse(text) as Json;
  } catch {
    json = { raw: text };
  }
  return { status: response.status, body: json };
};

let failures = 0;
const check = async (name: string, run: () => Promise<string | void>): Promise<boolean> => {
  try {
    const detail = await run();
    console.log(`  PASS  ${name}${detail ? `  (${detail})` : ""}`);
    return true;
  } catch (error) {
    failures += 1;
    console.log(`  FAIL  ${name}\n        ${error instanceof Error ? error.message : String(error)}`);
    return false;
  }
};
const assert = (condition: unknown, message: string): void => {
  if (!condition) throw new Error(message);
};

console.log("Payment gateway smoke test");

console.log("\nServices");
await check("merchant-back /health", async () => {
  const r = await fetchWithTimeout(`${MERCHANT.replace("/api/v1", "")}/health`);
  assert(r.status === 200, `status ${r.status}`);
});
await check("checkout-back /health", async () => {
  const r = await fetchWithTimeout(`${CHECKOUT.replace("/api/v1", "")}/health`);
  assert(r.status === 200, `status ${r.status}`);
});
await check("fake-rails-back /health", async () => {
  const r = await fetchWithTimeout(`${FAKE}/health`);
  assert(r.status === 200, `status ${r.status}`);
});
for (const [name, p] of PORTALS) {
  await check(`${name} served on :${p}`, async () => {
    const r = await fetchWithTimeout(`http://127.0.0.1:${p}/`);
    assert(r.status === 200 && (await r.text()).toLowerCase().includes("<html"), `status ${r.status}`);
  });
}
// The browser talks to the portal origin and Vite preview proxies `/api` to
// the edge. A portal that serves HTML but not the proxy would look healthy
// while every sign-in fails.
await check("merchant portal proxies /api to the merchant edge", async () => {
  const r = await fetchWithTimeout(`http://127.0.0.1:${port("MERCHANT_FRONT_PORT", 5102)}/api/v1/merchant/sandbox/payments`);
  assert(r.status === 401 || r.status === 403, `status ${r.status} (expected the edge's 401/403, not the portal shell)`);
});

console.log("\nSecurity");
await check("core-back refuses a client without a certificate (mTLS enforced)", async () => {
  let accepted = false;
  try {
    const r = await fetchWithTimeout(`${CORE_URL}/health`, { tls: { rejectUnauthorized: false } } as RequestInit);
    accepted = r.status < 500;
  } catch {
    accepted = false; // handshake rejected - what we want
  }
  assert(!accepted, "core-back answered a request that carried no client certificate");
});
await check("merchant API refuses a request without credentials", async () => {
  const r = await call("GET", `${MERCHANT}/merchant/sandbox/payments`);
  assert(r.status === 401 || r.status === 403, `status ${r.status}`);
});
await check("merchant API refuses an invalid pg_live_ token", async () => {
  const r = await call("POST", `${MERCHANT}/external/links`, { authorization: "Bearer pg_live_invalidinvalidinvalidinvalid" }, {
    title: "x", amount: "1.000", currency: "LYD",
  });
  assert(r.status === 401 || r.status === 403, `status ${r.status}`);
});

console.log("\nSimulated payment (Sandbox plane + Fake Rails)");
let session: Record<string, string> = {};
let applicationId = "";
let linkKey = "";
let attemptId = "";
let reference = "";

await check("merchant logs in", async () => {
  const r = await call("POST", `${MERCHANT}/merchant/auth/login`, {}, {
    identifier: "dev-merchant@payment-gateway.local",
    password: secret("DEV_PASSWORD"),
  });
  assert(r.status === 200 && r.body.token, `status ${r.status} ${JSON.stringify(r.body).slice(0, 120)}`);
  session = { authorization: `Bearer ${r.body.token}` };
});
await check("Sandbox Studio demo data is seeded", async () => {
  await call("POST", `${MERCHANT}/merchant/sandbox/seed-demo`, session, {}); // idempotent: already seeded is fine
  const apps = await call("GET", `${MERCHANT}/merchant/sandbox/applications`, session);
  assert(apps.status === 200 && apps.body.applications?.length > 0, `no sandbox application (status ${apps.status})`);
  applicationId = apps.body.applications[0].id;
});
await check("merchant creates a Sandbox payment link (sbx_)", async () => {
  const r = await call("POST", `${MERCHANT}/merchant/sandbox/links`, session, {
    applicationId,
    title: "Smoke test payment",
    amount: "25.000",
    currency: "LYD",
    idempotencyKey: `smoke-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
  });
  assert(r.status === 201 && String(r.body.key).startsWith("sbx_"), `status ${r.status} ${JSON.stringify(r.body).slice(0, 120)}`);
  linkKey = r.body.key;
  return linkKey;
});
await check("payer opens the checkout page and sees the Edfali rail", async () => {
  const r = await call("GET", `${CHECKOUT}/pay/${linkKey}`);
  assert(r.status === 200, `status ${r.status}`);
  assert(String(r.body.totalAmount ?? r.body.amount).startsWith("25"), `unexpected amount ${r.body.totalAmount}`);
  assert((r.body.visibleRails as Json[]).some((rail) => rail.code === "edfali"), "edfali rail not offered");
});
await check("payer starts the Edfali payment (OTP sent)", async () => {
  const r = await call("POST", `${CHECKOUT}/pay/${linkKey}/initiate`, {}, {
    railCode: "edfali",
    formData: { customer_mobile: PERSONA_MOBILE, otp: "0000" },
    idempotencyKey: `smoke-init-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
  });
  assert(r.status === 201 && r.body.clientAction?.kind === "SHOW_OTP_FORM", `status ${r.status} ${JSON.stringify(r.body).slice(0, 160)}`);
  attemptId = r.body.attemptId;
  reference = r.body.reference;
  return reference;
});
await check("payer enters the OTP shown by Fake Rails -> payment SUCCEEDED", async () => {
  const login = await call("POST", `${FAKE}/portal-api/auth/login`, {}, {
    username: "tester_admin",
    password: secret("FAKE_RAILS_ADMIN_PASSWORD"),
  });
  assert(login.status === 200, `Fake Rails login failed (${login.status})`);
  const tx = await call("GET", `${FAKE}/portal-api/transactions?limit=10`, { authorization: `Bearer ${login.body.token}` });
  const row = (tx.body.rows as Json[]).find((t) => t.our_reference === reference);
  assert(row?.expected_otp, "Fake Rails has no transaction for this reference (reference was not delivered to the gateway)");
  const confirm = await call("POST", `${CHECKOUT}/pay/${linkKey}/logs/${attemptId}/confirm`, {}, {
    otp: row!.expected_otp,
    idempotencyKey: `smoke-confirm-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
  });
  assert(confirm.status === 200 && confirm.body.status === "SUCCEEDED", `confirm -> ${confirm.status} ${confirm.body.status} ${confirm.body.canonicalError ?? ""}`);
});
await check("merchant sees the SUCCEEDED payment", async () => {
  const r = await call("GET", `${MERCHANT}/merchant/sandbox/payments?pageSize=50`, session);
  assert(r.status === 200, `status ${r.status}`);
  const payment = (r.body.payments as Json[]).find((p) => p.reference === reference);
  assert(payment, "payment not listed for the merchant");
  assert(payment!.status === "SUCCEEDED", `status ${payment!.status}`);
});

console.log("\nNegative control");
await check("a wrong OTP does not complete a payment", async () => {
  const link = await call("POST", `${MERCHANT}/merchant/sandbox/links`, session, {
    applicationId,
    title: "Smoke test wrong OTP",
    amount: "10.000",
    currency: "LYD",
    idempotencyKey: `smoke-neg-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
  });
  const key = link.body.key as string;
  const init = await call("POST", `${CHECKOUT}/pay/${key}/initiate`, {}, {
    railCode: "edfali",
    formData: { customer_mobile: UNKNOWN_MOBILE, otp: "0000" },
    idempotencyKey: `smoke-neg-init-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
  });
  assert(init.status === 201, `initiate ${init.status}`);
  const confirm = await call("POST", `${CHECKOUT}/pay/${key}/logs/${init.body.attemptId}/confirm`, {}, {
    otp: "0000",
    idempotencyKey: `smoke-neg-conf-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
  });
  assert(typeof confirm.body.status === "string" && confirm.body.status !== "SUCCEEDED", `a made-up OTP produced ${confirm.body.status ?? confirm.status}`);
  return `status ${confirm.body.status}`;
});

console.log(failures === 0 ? "\nALL CHECKS PASSED" : `\n${failures} CHECK(S) FAILED`);
process.exit(failures === 0 ? 0 : 1);
