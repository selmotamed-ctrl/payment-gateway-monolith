export const useI18n = () => {
    const { data } = useCompanionData();
    const lang = computed(() => data.value.settings.language);
    const dir = computed(() => (lang.value === "ar" ? "rtl" : "ltr"));
    const L = (key: string, vars?: Record<string, string | number>): string => {
        const message = messages[key];
        let text = message?.[lang.value] ?? message?.en ?? key;
        if (vars) {
            for (const [name, value] of Object.entries(vars)) {
                text = text.replaceAll(`{${name}}`, String(value));
            }
        }
        return text;
    };
    return { lang, dir, L, t: L };
};

