const INITIAL_STATE: [u32; 8] = [
    0x6a09_e667,
    0xbb67_ae85,
    0x3c6e_f372,
    0xa54f_f53a,
    0x510e_527f,
    0x9b05_688c,
    0x1f83_d9ab,
    0x5be0_cd19,
];

fn compress(state: &mut [u32; 8], block: &[u8]) {
    let mut schedule = [0u32; 64];
    for (index, chunk) in block.as_chunks::<4>().0.iter().take(16).enumerate() {
        schedule[index] = u32::from_be_bytes(*chunk);
    }
    for index in 16..64 {
        let first = schedule[index - 15];
        let second = schedule[index - 2];
        let s0 = first.rotate_right(7) ^ first.rotate_right(18) ^ (first >> 3);
        let s1 = second.rotate_right(17) ^ second.rotate_right(19) ^ (second >> 10);
        schedule[index] = schedule[index - 16]
            .wrapping_add(s0)
            .wrapping_add(schedule[index - 7])
            .wrapping_add(s1);
    }

    let mut a = state[0];
    let mut b = state[1];
    let mut c = state[2];
    let mut d = state[3];
    let mut e = state[4];
    let mut f = state[5];
    let mut g = state[6];
    let mut h = state[7];

    for index in 0..64 {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let choice = (e & f) ^ ((!e) & g);
        let temp1 = h
            .wrapping_add(s1)
            .wrapping_add(choice)
            .wrapping_add(K[index])
            .wrapping_add(schedule[index]);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let majority = (a & b) ^ (a & c) ^ (b & c);
        let temp2 = s0.wrapping_add(majority);

        h = g;
        g = f;
        f = e;
        e = d.wrapping_add(temp1);
        d = c;
        c = b;
        b = a;
        a = temp1.wrapping_add(temp2);
    }

    state[0] = state[0].wrapping_add(a);
    state[1] = state[1].wrapping_add(b);
    state[2] = state[2].wrapping_add(c);
    state[3] = state[3].wrapping_add(d);
    state[4] = state[4].wrapping_add(e);
    state[5] = state[5].wrapping_add(f);
    state[6] = state[6].wrapping_add(g);
    state[7] = state[7].wrapping_add(h);
}

/// SHA-256 of `data`.
#[must_use]
pub fn digest(data: &[u8]) -> [u8; 32] {
    let mut state = INITIAL_STATE;
    let bit_len = (data.len() as u64).wrapping_mul(8);
    let mut padded = Vec::with_capacity(data.len() + 72);
    padded.extend_from_slice(data);
    padded.push(0x80);
    while padded.len() % 64 != 56 {
        padded.push(0);
    }
    padded.extend_from_slice(&bit_len.to_be_bytes());

    for block in padded.as_chunks::<64>().0 {
        compress(&mut state, block);
    }

    let mut out = [0u8; 32];
    for (index, word) in state.iter().enumerate() {
        let start = index * 4;
        out[start..start + 4].copy_from_slice(&word.to_be_bytes());
    }
    out
}

/// Lower-case hex SHA-256, exactly `digest("hex")` in Node.
#[must_use]
pub fn digest_hex(data: &[u8]) -> String {
    let mut out = String::with_capacity(64);
    for byte in digest(data) {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nist_vectors() {
        assert_eq!(
            digest_hex(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            digest_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            digest_hex(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }

    #[test]
    fn padding_boundaries() {
        // 55, 56 and 63 bytes exercise the length-encoding edge of the padding rule.
        for length in [0usize, 1, 55, 56, 63, 64, 65, 1000] {
            let data = vec![b'a'; length];
            let first = digest_hex(&data);
            let second = digest_hex(&data);
            assert_eq!(first, second);
            assert_eq!(first.len(), 64);
        }
        // Incremental sanity: the digest depends on every byte.
        assert_ne!(digest_hex(b"abc"), digest_hex(b"abd"));
    }
}
