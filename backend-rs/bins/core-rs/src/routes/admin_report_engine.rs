/// Register one `GET` policy and its handler.
fn get(path: &str, ts_origin: &str, authorities: &[&str], handler: CustomHandler) -> MountedRoute {
    MountedRoute {
        policy: Policy::new("GET", path, Channel::Admin, Authn::Session, ts_origin)
            .authorities(authorities)
            .body(BodyRule::None),
        handler: Handler::Custom(handler),
        guard: PrincipalGuard::Staff,
    }
}

/// The authenticated staff principal, or the TS refusal.
fn staff(principal: Option<&Principal>) -> Result<&Principal, ApiError> {
    let principal = principal.ok_or_else(|| {
        ApiError::new(
            401,
            "AUTH_REQUIRED",
            "A bearer token is required for this endpoint",
        )
    })?;
    principal.require_staff().map_err(crate::auth::api_error)?;
    Ok(principal)
}

/// `requireAuthorities`: the handler-level copy of the policy check (the dispatcher already runs
/// the same list for a mounted request; tests call handlers directly).
fn require(principal: &Principal, authorities: &[&str]) -> Result<(), ApiError> {
    principal
        .require_authorities(authorities)
        .map_err(crate::auth::api_error)
}

/// `holdsAny(principal, list)` with the staff wildcard.
fn holds_any(principal: &Principal, authorities: &[&str]) -> bool {
    let wildcard = principal
        .authorities
        .iter()
        .any(|authority| authority == "*")
        && principal.is_staff();
    wildcard
        || authorities
            .iter()
            .any(|required| principal.authorities.iter().any(|held| held == required))
}

fn actor_of(principal: &Principal) -> Actor<'_> {
    Actor {
        role: principal.role.as_deref().unwrap_or("UNKNOWN"),
        authorities: &principal.authorities,
    }
}

/// TS `Number(value) || fallback` clamped to `[1, max]`.
fn positive(query: &Query, key: &str, fallback: u32, max: u32) -> u32 {
    match query.non_empty(key).and_then(|raw| raw.parse::<f64>().ok()) {
        Some(value) if value.is_finite() && value != 0.0 => {
            let clamped = value.max(1.0).min(f64::from(max));
            #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
            let result = clamped as u32;
            result.max(1)
        }
        _ => fallback,
    }
}

fn page_window(query: &Query, default_size: u32, max_size: u32) -> (usize, usize) {
    let page = positive(query, "page", 1, u32::MAX) as usize;
    let size = positive(query, "pageSize", default_size, max_size) as usize;
    (page.saturating_sub(1) * size, size)
}

fn slice_page<T>(items: Vec<T>, offset: usize, size: usize) -> Vec<T> {
    items.into_iter().skip(offset).take(size).collect()
}

fn sort_direction(query: &Query) -> &'static str {
    if query.get("sortDirection") == Some("asc") {
        "ASC"
    } else {
        "DESC"
    }
}

fn search_term(query: &Query) -> String {
    query
        .get("search")
        .map(str::trim)
        .unwrap_or_default()
        .to_owned()
}

/// Wrap an async handler body in the dispatcher's future type and error envelope.
fn respond<'a, F>(request: &'a HttpRequest, future: F) -> HandlerFuture<'a>
where
    F: std::future::Future<Output = Result<Value, ApiError>> + 'a,
{
    Box::pin(async move {
        match future.await {
            Ok(value) => common::json_ok(&value),
            Err(error) => crate::http::error_response(request, error),
        }
    })
}

fn database(error: sqlx::Error) -> ApiError {
    common::database_error(error)
}

fn decode<T>(result: Result<T, sqlx::Error>) -> Result<T, ApiError> {
    result.map_err(database)
}

