pub fn specs<'a>(
    state: &'a AppState,
    request: &'a HttpRequest,
    principal: Option<&'a Principal>,
    _payload: Payload,
) -> HandlerFuture<'a> {
    respond(request, async move {
        let principal = staff(principal)?;
        require(principal, SPEC_READ)?;
        let query = Query::parse(request.query_string());
        let mut builder = QueryBuilder::new(format!(
            "SELECT {REPORT_COLUMNS} FROM report_definition_specs WHERE true"
        ));
        if let Some(code) = query.non_empty("code") {
            builder.push(" AND code = ").push_bind(code.to_owned());
        }
        if let Some(status) = query.non_empty("status") {
            builder
                .push(" AND status::text = ")
                .push_bind(status.to_owned());
        }
        builder.push(" ORDER BY code ASC, version DESC LIMIT 200");
        let rows = decode(builder.build().fetch_all(&state.pools.main).await)?;
        let specs = rows
            .iter()
            .map(ReportRow::from_row)
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?
            .iter()
            .map(ReportRow::list_json)
            .collect::<Vec<_>>();
        Ok(json!({ "specs": specs }))
    })
}

pub fn spec_detail<'a>(
    state: &'a AppState,
    request: &'a HttpRequest,
    principal: Option<&'a Principal>,
    _payload: Payload,
) -> HandlerFuture<'a> {
    respond(request, async move {
        let principal = staff(principal)?;
        require(principal, SPEC_READ)?;
        let id = path_param(request.path(), "/internal/admin/report-engine/specs/")?;
        let row = load_report(state, id).await?;
        Ok(row.detail_json())
    })
}

fn path_param(path: &str, prefix: &str) -> Result<Uuid, ApiError> {
    let raw = path.strip_prefix(prefix).unwrap_or_default();
    let raw = raw.split('/').next().unwrap_or_default();
    Uuid::parse_str(raw)
        .map_err(|_| ApiError::new(400, "INVALID_BODY", "The path identifier must be a UUID"))
}

async fn load_report(state: &AppState, id: Uuid) -> Result<ReportRow, ApiError> {
    let row = sqlx::query(sqlx::AssertSqlSafe(format!(
        "SELECT {REPORT_COLUMNS} FROM report_definition_specs WHERE id = $1"
    )))
    .bind(id)
    .fetch_optional(&state.pools.main)
    .await
    .map_err(database)?;
    row.as_ref()
        .map(ReportRow::from_row)
        .transpose()
        .map_err(database)?
        .ok_or_else(|| {
            ApiError::new(
                404,
                "REPORT_SPEC_NOT_FOUND",
                "The report spec does not exist",
            )
        })
}

/// `buildReportMigrationPrompt` / `buildChromeMigrationPrompt` are released artefacts of P8-T01;
/// the shell answers its unported-route error instead of inventing a prompt body.
fn migration_prompt_unavailable(artifact: &str) -> ApiError {
    ApiError::new(
        501,
        "NOT_IMPLEMENTED_ROUTE",
        "The migration prompt requires the authoring transcript builder, which is not ported yet",
    )
    .with_details(json!({ "artifact": artifact, "dependency": "P8-T01" }))
}

/// `GET /report-engine/specs/:id/migration-prompt`.
pub fn spec_migration_prompt<'a>(
    state: &'a AppState,
    request: &'a HttpRequest,
    principal: Option<&'a Principal>,
    _payload: Payload,
) -> HandlerFuture<'a> {
    respond(request, async move {
        let principal = staff(principal)?;
        require(principal, SPEC_PROMPT_AUTHORITIES)?;
        let id = path_param(request.path(), "/internal/admin/report-engine/specs/")?;
        let row = load_report(state, id).await?;
        if row.compatibility().status.as_str() == "COMPATIBLE" {
            return Err(ApiError::new(
                409,
                "REPORT_SPEC_NOT_MIGRATABLE",
                "This report spec does not need migration",
            ));
        }
        Err(migration_prompt_unavailable("ReportTranscriptBuilder"))
    })
}

