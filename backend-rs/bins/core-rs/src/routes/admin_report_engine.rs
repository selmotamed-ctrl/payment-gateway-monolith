pub fn specs_needs_migration<'a>(
    state: &'a AppState,
    request: &'a HttpRequest,
    principal: Option<&'a Principal>,
    _payload: Payload,
) -> HandlerFuture<'a> {
    respond(request, async move {
        let principal = staff(principal)?;
        require(principal, MIGRATION_READ)?;
        let query = Query::parse(request.query_string());
        let source = query.get("source").unwrap_or("ALL").to_ascii_uppercase();
        let search = query
            .get("search")
            .map(str::trim)
            .unwrap_or_default()
            .to_lowercase();
        let (offset, size) = page_window(&query, 20, 200);

        let staff_rows = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {REPORT_COLUMNS} FROM report_definition_specs \
             WHERE status::text <> 'ARCHIVED' ORDER BY code ASC, version DESC"
        )))
        .fetch_all(&state.pools.main)
        .await
        .map_err(database)?;
        let staff_rows = staff_rows
            .iter()
            .map(ReportRow::from_row)
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?;
        let mut staff_latest: BTreeMap<String, ReportRow> = BTreeMap::new();
        for row in staff_rows {
            let replace = match staff_latest.get(&row.code) {
                None => true,
                Some(existing) => row.is_latest_published && !existing.is_latest_published,
            };
            if replace {
                staff_latest.insert(row.code.clone(), row);
            }
        }

        let merchant_rows = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {MERCHANT_SPEC_COLUMNS} FROM merchant_report_specs \
             WHERE status::text <> 'ARCHIVED' \
             ORDER BY merchant_id ASC, code ASC, version DESC"
        )))
        .fetch_all(&state.pools.main)
        .await
        .map_err(database)?;
        let merchant_rows = merchant_rows
            .iter()
            .map(MerchantSpecRow::from_row)
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?;
        let mut merchant_latest: BTreeMap<(Uuid, String), MerchantSpecRow> = BTreeMap::new();
        for row in merchant_rows {
            let key = (row.merchant_id, row.code.clone());
            let replace = match merchant_latest.get(&key) {
                None => true,
                Some(existing) => row.is_latest_published && !existing.is_latest_published,
            };
            if replace {
                merchant_latest.insert(key, row);
            }
        }

        let mut items: Vec<(DateTime<Utc>, Value)> = Vec::new();
        if source == "ALL" || source == "STAFF" {
            for row in staff_latest.values() {
                let compatibility = row.compatibility();
                if compatibility.status.as_str() == "COMPATIBLE" {
                    continue;
                }
                if !search.is_empty()
                    && !format!("{} {}", row.code, row.category)
                        .to_lowercase()
                        .contains(&search)
                {
                    continue;
                }
                items.push((
                    row.updated_at,
                    json!({
                        "id": row.id,
                        "source": "STAFF",
                        "code": row.code,
                        "version": row.version,
                        "category": row.category,
                        "audienceScope": row.audience_scope,
                        "status": row.status,
                        "isLatestPublished": row.is_latest_published,
                        "compatibility": model::report_compatibility_json(&compatibility),
                        "updatedAt": model::iso(row.updated_at),
                        "promptAvailable": true,
                    }),
                ));
            }
        }
        if source == "ALL" || source == "MERCHANT" {
            for row in merchant_latest.values() {
                let compatibility = row.compatibility();
                if compatibility.status.as_str() == "COMPATIBLE" {
                    continue;
                }
                if !search.is_empty()
                    && !format!("{} {}", row.code, row.category)
                        .to_lowercase()
                        .contains(&search)
                {
                    continue;
                }
                items.push((
                    row.updated_at,
                    json!({
                        "id": row.id,
                        "source": "MERCHANT",
                        "merchantId": row.merchant_id,
                        "code": row.code,
                        "version": row.version,
                        "category": row.category,
                        "audienceScope": "MERCHANT_FACING",
                        "status": row.status,
                        "isLatestPublished": row.is_latest_published,
                        "compatibility": model::report_compatibility_json(&compatibility),
                        "updatedAt": model::iso(row.updated_at),
                        "promptAvailable": true,
                    }),
                ));
            }
        }
        items.sort_by_key(|entry| std::cmp::Reverse(entry.0));
        let total = items.len();
        let specs = slice_page(
            items.into_iter().map(|(_, value)| value).collect(),
            offset,
            size,
        );
        Ok(json!({ "specs": specs, "total": total }))
    })
}

