struct MerchantSpecRow {
    id: Uuid,
    merchant_id: Uuid,
    code: String,
    version: i32,
    category: String,
    status: String,
    is_latest_published: bool,
    spec_json: Value,
    engine_version: String,
    spec_schema_version: String,
    created_at: DateTime<Utc>,
    published_at: Option<DateTime<Utc>>,
    updated_at: DateTime<Utc>,
}

impl MerchantSpecRow {
    fn from_row(row: &PgRow) -> Result<Self, sqlx::Error> {
        Ok(Self {
            id: row.try_get("id")?,
            merchant_id: row.try_get("merchant_id")?,
            code: row.try_get("code")?,
            version: row.try_get("version")?,
            category: row.try_get("category")?,
            status: row.try_get("status")?,
            is_latest_published: row.try_get("is_latest_published")?,
            spec_json: row.try_get("spec_json")?,
            engine_version: row.try_get("engine_version")?,
            spec_schema_version: row.try_get("spec_schema_version")?,
            created_at: row.try_get("created_at")?,
            published_at: row.try_get("published_at")?,
            updated_at: row.try_get("updated_at")?,
        })
    }

    fn compatibility(&self) -> pg_report_engine::ReportCompatibility {
        pg_report_engine::classify_stored_report_spec(pg_report_engine::StoredSpecInput {
            spec_json: &self.spec_json,
            stored_engine_version: Some(self.engine_version.as_str()),
            stored_spec_version: Some(self.spec_schema_version.as_str()),
        })
    }
}

/// Load one merchant report spec (`GET /merchant-reports/:id/migration-prompt`).
