pub fn catalog<'a>(
    state: &'a AppState,
    request: &'a HttpRequest,
    principal: Option<&'a Principal>,
    _payload: Payload,
) -> HandlerFuture<'a> {
    respond(request, async move {
        let principal = staff(principal)?;
        let query = Query::parse(request.query_string());
        let audience = query.get("audience").unwrap_or("ALL");
        let (offset, size) = page_window(&query, 20, 200);
        let search = search_term(&query);
        let sort_key = query.get("sortKey").unwrap_or_default().to_owned();
        let direction = sort_direction(&query);

        let mut builder = QueryBuilder::new(format!(
            "SELECT {REPORT_COLUMNS} FROM report_definition_specs \
             WHERE status::text = 'PUBLISHED' AND is_latest_published = true"
        ));
        match audience {
            "BACKOFFICE_INTERNAL" => {
                builder.push(" AND audience_scope::text IN ('BACKOFFICE_INTERNAL', 'BOTH')");
            }
            "MERCHANT_FACING" => {
                builder.push(" AND audience_scope::text IN ('MERCHANT_FACING', 'BOTH')");
            }
            _ => {}
        }
        if !search.is_empty() {
            builder
                .push(" AND (code ILIKE '%' || ")
                .push_bind(search.clone())
                .push(" || '%' OR category ILIKE '%' || ")
                .push_bind(search)
                .push(" || '%')");
        }
        builder.push(" ORDER BY ");
        builder.push(match sort_key.as_str() {
            "version" => "version",
            "category" => "category",
            "report" => "code",
            _ => "updated_at",
        });
        builder.push(" ");
        builder.push(direction);

        let rows = decode(builder.build().fetch_all(&state.pools.main).await)?;
        let specs = rows
            .iter()
            .map(ReportRow::from_row)
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?;
        let chrome = load_chrome_registry(state).await?;
        let actor = actor_of(principal);

        let mut allowed = Vec::new();
        let mut broken_report_specs = 0_u32;
        let mut blocked_by_chrome = 0_u32;
        for row in specs {
            if !row.allowed(actor) {
                continue;
            }
            let compatibility = row.compatibility();
            if compatibility.status.as_str() != "COMPATIBLE" {
                broken_report_specs += 1;
                continue;
            }
            if !chrome.dependency_ready(&row.spec_json) {
                blocked_by_chrome += 1;
                continue;
            }
            allowed.push(row.catalog_json());
        }
        let total = allowed.len();
        let reports = slice_page(allowed, offset, size);
        Ok(json!({
            "reports": reports,
            "total": total,
            "health": {
                "brokenReportSpecs": broken_report_specs,
                "brokenChromeSpecs": chrome.broken_by_code.len(),
                "reportsBlockedByChrome": blocked_by_chrome,
            },
        }))
    })
}

async fn load_chrome_registry(state: &AppState) -> Result<ChromeRegistry, ApiError> {
    let rows = sqlx::query(sqlx::AssertSqlSafe(format!(
        "SELECT {CHROME_COLUMNS} FROM report_chrome_specs \
         WHERE status::text = 'PUBLISHED' \
         ORDER BY chrome_type ASC, code ASC, version DESC"
    )))
    .fetch_all(&state.pools.main)
    .await
    .map_err(database)?;
    let chrome = rows
        .iter()
        .map(ChromeRow::from_row)
        .collect::<Result<Vec<_>, _>>()
        .map_err(database)?;
    Ok(ChromeRegistry::from_published(chrome))
}

