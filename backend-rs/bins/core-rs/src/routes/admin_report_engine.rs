//! Admin Report Studio read routes (P4 `admin.ts`/P8 Report Studio slice).
//!
//! Port of the `GET` handlers of `core-back/api/internal/adminReportEngine.ts` that do not need
//! the authoring/transcript engine. Every route is mounted under `/internal/admin/report-engine`
//! on the admin channel with the exact TS authorities (OR semantics, as `requireAuthorities`).
//!
//! | Rust handler | TS source |
//! | :--- | :--- |
//! | [`catalog`] | `:1902` published catalog, audience filter, per-report policy |
//! | [`specs`] | `:1175` authoring version list |
//! | [`spec_detail`] | `:1351` one spec (body + verification) |
//! | [`specs_needs_migration`] | `:1215` staff + merchant migration status |
//! | [`executions`] | `:1559` execution audit |
//! | [`aml_bypass_pending`] | `:1756` pending REPORT_AML_BYPASS approvals |
//! | [`chrome_list`] | `:2213` header/footer list (published unless author) |
//! | [`chrome_detail`] | `:2458` one chrome (published unless author) |
//! | [`chrome_needs_migration`] | `:2258` chrome migration status and defaults |
//! | [`merchant_reports`] | `:2670` merchant reporting-line oversight |
//! | [`merchant_executions`] | `:2728` merchant execution audit |
//! | [`autocomplete_source`] | `:1992` host autocomplete source (allow-list) |
//! | [`spec_migration_prompt`] | `:1287` 404/409 gate; prompt needs P8-T01 |
//! | [`merchant_migration_prompt`] | `:1317` 404/409 gate; prompt needs P8-T01 |
//! | [`chrome_migration_prompt`] | `:2398` 404/409 gate; prompt needs P8-T01 |
//!
//! Still deferred (no released artefact in the tree):
//!
//! - `GET /report-engine/transcript` (`:847`): its body is the authoring transcript generated by
//!   `lib/reportEngineSdk/transcript/{ReportTranscriptBuilder,ChromeTranscriptBuilder}.ts`, which
//!   `pg-report-engine` does not carry yet (P8-T01). The TS handler always builds it from the live
//!   host config (including `generatedAt`), so a committed snapshot cannot reproduce it.
//!
//! The three `migration-prompt` routes are mounted because their 404 and "do not need migration"
//! 409 branches are independent of the transcript. For a spec/chrome that does need migration the
//! handler answers the shell's `501 NOT_IMPLEMENTED_ROUTE` with the missing artefact in
//! `details`; it never fabricates a prompt. The same deferral applies to the prompt text.
//!
//! Other deviations of this slice:
//!
//! - `assetDataUrls` in the chrome views is `{}` until the shared object-storage asset port is
//!   wired (P8-T02). The bundle id is still returned; no asset bytes or paths are logged.
//! - The returned `spec` of a compatible stored row is the stored `spec_json`, not a
//!   zod-normalised copy (the Rust SDK view does not apply every schema default yet).
//! - Policy paths use TS placeholders (`:id`) for parameterised routes. The P3 dispatcher matches
//!   exact paths, so those handlers are exercised directly until the coordinator wires pattern
//!   matching into the shared router.
//! - Nothing in this module logs a report spec, a chrome body or a tenant identifier.

