pub fn chrome_needs_migration<'a>(
    state: &'a AppState,
    request: &'a HttpRequest,
    principal: Option<&'a Principal>,
    _payload: Payload,
) -> HandlerFuture<'a> {
    respond(request, async move {
        let principal = staff(principal)?;
        require(principal, CHROME_MIGRATION_READ)?;
        let query = Query::parse(request.query_string());
        let (offset, size) = page_window(&query, 20, 200);
        let search = query
            .get("search")
            .map(str::trim)
            .unwrap_or_default()
            .to_lowercase();

        let rows = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {CHROME_COLUMNS} FROM report_chrome_specs \
             WHERE status::text <> 'ARCHIVED' \
             ORDER BY chrome_type ASC, code ASC, version DESC"
        )))
        .fetch_all(&state.pools.main)
        .await
        .map_err(database)?;
        let rows = rows
            .iter()
            .map(ChromeRow::from_row)
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?;
        let mut latest: BTreeMap<String, ChromeRow> = BTreeMap::new();
        for row in &rows {
            latest
                .entry(row.code.clone())
                .or_insert_with(|| row.clone());
        }

        let staff_reports = sqlx::query(
            "SELECT code, spec_json FROM report_definition_specs \
             WHERE status::text = 'PUBLISHED' AND is_latest_published = true",
        )
        .fetch_all(&state.pools.main)
        .await
        .map_err(database)?;
        let staff_layouts: Vec<(String, model::LayoutSelection)> = staff_reports
            .iter()
            .map(
                |row| -> Result<(String, model::LayoutSelection), sqlx::Error> {
                    let spec: Value = row.try_get("spec_json")?;
                    Ok((row.try_get("code")?, layout_selection(&spec)))
                },
            )
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?;

        let merchant_reports = sqlx::query(
            "SELECT merchant_id, code, spec_json FROM merchant_report_specs \
             WHERE status::text = 'PUBLISHED' AND is_latest_published = true",
        )
        .fetch_all(&state.pools.main)
        .await
        .map_err(database)?;
        let merchant_layouts: Vec<(Uuid, String, model::LayoutSelection)> = merchant_reports
            .iter()
            .map(
                |row| -> Result<(Uuid, String, model::LayoutSelection), sqlx::Error> {
                    let spec: Value = row.try_get("spec_json")?;
                    Ok((
                        row.try_get("merchant_id")?,
                        row.try_get("code")?,
                        layout_selection(&spec),
                    ))
                },
            )
            .collect::<Result<Vec<_>, _>>()
            .map_err(database)?;

        let merchant_defaults = sqlx::query(
            "SELECT merchant_id, chrome_type::text AS chrome_type \
               FROM merchant_report_chrome_specs \
              WHERE status::text = 'PUBLISHED' AND is_default_for_merchant = true",
        )
        .fetch_all(&state.pools.main)
        .await
        .map_err(database)?;
        let merchant_default_types: std::collections::BTreeSet<(Uuid, String)> = merchant_defaults
            .iter()
            .map(|row| -> Result<(Uuid, String), sqlx::Error> {
                Ok((row.try_get("merchant_id")?, row.try_get("chrome_type")?))
            })
            .collect::<Result<_, _>>()
            .map_err(database)?;

        let mut items = Vec::new();
        for row in latest.values() {
            let compatibility = row.compatibility();
            if compatibility.status == "COMPATIBLE" {
                continue;
            }
            if !search.is_empty()
                && !format!("{} {}", row.code, row.name)
                    .to_lowercase()
                    .contains(&search)
            {
                continue;
            }
            let mut impacted_codes = std::collections::BTreeSet::new();
            let mut impacted_keys = std::collections::BTreeSet::new();
            for (code, layout) in &staff_layouts {
                let is_impacted = if row.chrome_type == "HEADER" {
                    (layout.header_mode == "SPECIFIC_CHROME_CODE"
                        && layout.header_code.as_deref() == Some(row.code.as_str()))
                        || (layout.header_mode == "GLOBAL_DEFAULT"
                            && (row.is_default_global || row.default_revoked_at.is_some()))
                } else {
                    (layout.footer_mode == "SPECIFIC_CHROME_CODE"
                        && layout.footer_code.as_deref() == Some(row.code.as_str()))
                        || (layout.footer_mode == "GLOBAL_DEFAULT"
                            && (row.is_default_global || row.default_revoked_at.is_some()))
                };
                if is_impacted {
                    impacted_codes.insert(code.clone());
                    impacted_keys.insert(format!("staff:{code}"));
                }
            }
            for (merchant_id, code, layout) in &merchant_layouts {
                let has_own_default =
                    merchant_default_types.contains(&(*merchant_id, row.chrome_type.clone()));
                let uses_platform_default =
                    !has_own_default && (row.is_default_global || row.default_revoked_at.is_some());
                let is_impacted = if row.chrome_type == "HEADER" {
                    (layout.header_mode == "SPECIFIC_CHROME_CODE"
                        && layout.header_code.as_deref() == Some(row.code.as_str()))
                        || (layout.header_mode == "GLOBAL_DEFAULT" && uses_platform_default)
                } else {
                    (layout.footer_mode == "SPECIFIC_CHROME_CODE"
                        && layout.footer_code.as_deref() == Some(row.code.as_str()))
                        || (layout.footer_mode == "GLOBAL_DEFAULT" && uses_platform_default)
                };
                if is_impacted {
                    impacted_codes.insert(code.clone());
                    impacted_keys.insert(format!("merchant:{merchant_id}:{code}"));
                }
            }
            let default_state = if row.is_default_global {
                "ACTIVE"
            } else if row.default_revoked_at.is_some() {
                "REVOKED"
            } else {
                "NONE"
            };
            items.push(json!({
                "id": row.id,
                "code": row.code,
                "version": row.version,
                "name": row.name,
                "chromeType": row.chrome_type,
                "status": row.status,
                "isDefaultGlobal": row.is_default_global,
                "defaultRevokedAt": model::iso_opt(row.default_revoked_at),
                "defaultRevokedReason": row.default_revoked_reason,
                "defaultState": default_state,
                "compatibility": compatibility.to_json(),
                "impactedReportCount": impacted_keys.len(),
                "impactedReportCodes": impacted_codes.iter().take(10).collect::<Vec<_>>(),
            }));
        }
        let total = items.len();
        let specs = slice_page(items, offset, size);
        let default_state = |chrome_type: &str| -> &'static str {
            let candidates: Vec<&ChromeRow> = rows
                .iter()
                .filter(|row| row.chrome_type == chrome_type)
                .collect();
            let active = candidates.iter().any(|row| {
                row.status == "PUBLISHED"
                    && row.is_default_global
                    && row.compatibility().status == "COMPATIBLE"
            });
            if active {
                return "ACTIVE";
            }
            let revoked = candidates.iter().any(|row| {
                row.status == "PUBLISHED"
                    && (row.is_default_global || row.default_revoked_at.is_some())
                    && row.compatibility().status != "COMPATIBLE"
            });
            if revoked {
                "REVOKED"
            } else {
                "MISSING"
            }
        };
        Ok(json!({
            "specs": specs,
            "total": total,
            "defaults": {
                "header": default_state("HEADER"),
                "footer": default_state("FOOTER"),
            },
        }))
    })
}

