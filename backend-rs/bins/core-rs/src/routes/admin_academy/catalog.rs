/// `EXPIRING_DAYS` of `team.ts`.
const EXPIRING_DAYS: i64 = 30;

/// `core-back/content/academy/catalog.json` (generated by the Guide/Academy extractor).
const CATALOG_JSON: &str = include_str!("../../../../../../core-back/content/academy/catalog.json");
