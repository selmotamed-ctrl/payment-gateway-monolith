//! Embedded Academy content, team projection and exam eligibility.
//!
//! Port of `core-back/engine/academy/{catalog,team}.ts` and `computeEligibility` in
//! `engine/academy/service.ts`.
//!
//! The catalogue and exam bank are the extractor outputs the TypeScript server loads from
//! `core-back/content/academy/`. Until `P9-T08` relocates them to `content/academy/`, this module
//! embeds those exact files at compile time (read-only; no copy is kept, so the two servers can
//! never drift). They are parsed once with [`std::sync::OnceLock`]; a broken file yields an empty
//! catalogue and the DB-free tests fail loudly.
//!
//! Only the members the read routes need are typed; unknown members are ignored.

#![forbid(unsafe_code)]

