impl Catalog {
    /// `trackOf`.
    #[must_use]
    pub fn track(&self, id: &str) -> Option<&CatalogTrack> {
        self.tracks.iter().find(|track| track.id == id)
    }

    /// `isTrackId`.
    #[must_use]
    pub fn has_track(&self, id: &str) -> bool {
        self.track(id).is_some()
    }

    /// `lessonTitle`.
    #[must_use]
    pub fn lesson_title(&self, id: &str) -> String {
        self.lessons
            .iter()
            .find(|lesson| lesson.id == id)
            .map_or_else(|| id.to_owned(), |lesson| lesson.title.clone())
    }

    /// `labOf`.
    #[must_use]
    pub fn lab(&self, id: &str) -> Option<&Lab> {
        self.labs.iter().find(|lab| lab.id == id)
    }

    /// `moduleTitle`.
    #[must_use]
    pub fn module_title(&self, id: &str) -> String {
        self.modules
            .iter()
            .find(|module| module.id == id)
            .map_or_else(|| id.to_owned(), |module| module.title.clone())
    }
}

